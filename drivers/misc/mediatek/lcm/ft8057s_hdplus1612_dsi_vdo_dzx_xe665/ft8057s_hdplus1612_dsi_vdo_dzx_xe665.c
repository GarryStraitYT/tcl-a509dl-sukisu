static void lcm_init(void)
{
	unsigned int size;

//Begin added by liangjiaqiang for CVSR-2695 on 2023-07-21
#ifdef CONFIG_SR_LCM_BIAS_IC_SUPPORT
	unsigned char cmd  = 0x0;
	unsigned char data = 0xFF;
	int ret = 0;
#endif
//End added by liangjiaqiang for CVSR-2695 on 2023-07-21
	
	printk("FT8057S DZX %s enter\n", __func__);
//guozhiliang add TP lcd sleep in PROXIMITY mode 
#if defined(CONFIG_TP_PROXIMITY_SLEEP_CONTROLL_IN_BSP)	
	tp_ps_work_skip_lcd_poweroff_flag=0;
#endif
//guozhiliang add TP lcd sleep in PROXIMITY mode 

//Begin added by liangjiaqiang for CVSR-2695 on 2023-07-21
#ifdef CONFIG_SR_LCM_BIAS_IC_SUPPORT
	SET_RESET_PIN(0);
	MDELAY(6);
	mtk_set_gpio_out(GPIO_LCD_BIAS_ENP, 1);
	cmd  = 0x00; //addr 0x00: VPOS Positive Voltage Output Setting Register
	data = 0x14; //data 0x0F: +5.9v real voltage is 5.8
	ret = lcm_bias_write_bytes(cmd, data);
	if (ret < 0)
		pr_err("ft8057s----dzx---cmd=%0x-- i2c write error-----\n", cmd);
	else
		pr_debug("ft8057s----dzx---cmd=%0x-- i2c write success-----\n", cmd);

	MDELAY(8);
	
	mtk_set_gpio_out(GPIO_LCD_BIAS_ENN, 1);
	cmd  = 0x01; //addr 0x01:VNEG Negative Voltage Output Setting Register
	data = 0x14; //data 0x0F: +5.9v real voltage is 5.8
	ret = lcm_bias_write_bytes(cmd, data);
	if (ret < 0)
		pr_err("ft8057s----dzx---cmd=%0x-- i2c write error-----\n", cmd);
	else
		pr_debug("ft8057s----dzx---cmd=%0x-- i2c write success-----\n", cmd);
		
	MDELAY(10);
	SET_RESET_PIN(1);
	MDELAY(6);
	SET_RESET_PIN(0);
	MDELAY(6);
	SET_RESET_PIN(1);
	MDELAY(6);
#else
	SET_RESET_PIN(0);
	MDELAY(6);
	display_bias_enable_VSP();	
	MDELAY(10);
    display_bias_enable_VSN();
    MDELAY(10);
	SET_RESET_PIN(1);
	MDELAY(6);
	SET_RESET_PIN(0);
	MDELAY(6);
	SET_RESET_PIN(1);
	MDELAY(6);
#endif
//End added by liangjiaqiang for CVSR-2695 on 2023-07-21

	size = sizeof(init_setting) /
		sizeof(struct LCM_setting_table);
		
	push_table(NULL, init_setting, size, 1);

}

