static void lcm_init(void)
{
	unsigned int size;
	
	printk("ft8057 gx %s enter\n", __func__);
	
	display_bias_enable_VSP();	
	MDELAY(5);	
	SET_RESET_PIN(0);	
	MDELAY(2);
	SET_RESET_PIN(1);
	MDELAY(8);
	display_bias_enable_VSN();
	MDELAY(1);
	SET_RESET_PIN(0);
	MDELAY(12);
	SET_RESET_PIN(1);
	MDELAY(12);   
   

	size = sizeof(init_setting) /
		sizeof(struct LCM_setting_table);
		
	push_table(NULL, init_setting, size, 1);

}

